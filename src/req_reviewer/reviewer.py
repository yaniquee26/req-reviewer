SYSTEM_PROMPT = PROMPTS["v1"]

MAX_QUESTIONS = 7
_ITEM = re.compile(r"^\s*(?:\d+[.)]|[-*•])\s*(.+)$")


def build_user_prompt(text: str) -> str:
    safe = text.replace("<data>", "").replace("</data>", "")
    return f"Требование:\n<data>\n{safe}\n</data>"


def parse_questions(answer: str) -> list[str]:
    if answer.strip().upper().startswith("НЕТ"):
        return []
    questions = []
    for line in answer.splitlines():
        m = _ITEM.match(line)
        if m:
            q = m.group(1).strip()
            if q and q not in questions:
                questions.append(q)
    return questions[:MAX_QUESTIONS]


def find_ambiguities(text: str, client, prompt: str = "v1") -> list[str]:
    if prompt not in PROMPTS:
        raise ValueError(f"Неизвестная версия подсказки: {prompt}")
    answer = client.chat(PROMPTS[prompt], build_user_prompt(text))
    return parse_questions(answer)